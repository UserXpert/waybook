CREATE TABLE stripe_sandbox_client_cards (
  tenant_id UUID NOT NULL,
  customer_id UUID NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  account_id TEXT NOT NULL CHECK (account_id ~ '^acct_[A-Za-z0-9]+$'),
  stripe_customer_id TEXT CHECK (stripe_customer_id ~ '^cus_[A-Za-z0-9]+$'),
  creation_key UUID NOT NULL DEFAULT gen_random_uuid(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  setup_id UUID UNIQUE,
  setup_return_url TEXT,
  setup_expires_at INTEGER,
  setup_actor_id UUID,
  consented_by UUID,
  consented_at TIMESTAMPTZ,
  setup_session_id TEXT CHECK (setup_session_id ~ '^cs_test_[A-Za-z0-9]+$'),
  card_brand TEXT CHECK (card_brand ~ '^[a-z0-9_]{1,32}$'),
  card_last4 TEXT CHECK (card_last4 ~ '^[0-9]{4}$'),
  PRIMARY KEY (tenant_id, customer_id, account_id),
  CHECK ((card_brand IS NULL) = (card_last4 IS NULL)),
  CHECK ((card_brand IS NULL) = (consented_by IS NULL)),
  CHECK ((consented_by IS NULL) = (consented_at IS NULL)),
  CHECK ((setup_id IS NULL) = (setup_return_url IS NULL)),
  CHECK ((setup_id IS NULL) = (setup_expires_at IS NULL)),
  CHECK ((setup_id IS NULL) = (setup_actor_id IS NULL)),
  CHECK (setup_id IS NOT NULL OR setup_session_id IS NULL)
);
